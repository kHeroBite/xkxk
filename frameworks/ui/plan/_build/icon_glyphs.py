def _arc(cx, cy, r, a0, a1, n=None):
    """화면 좌표(y 아래)에서 a0→a1 도(시계 방향 증가) 원호 점 목록."""
    n = n or max(4, int(abs(a1 - a0) / 360 * max(16, r * 5)))
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
            for i in range(n + 1)]


def C(cx, cy, r):
    return _arc(cx, cy, r, 0, 360)[:-1]


def E(cx, cy, rx, ry):
    return [(cx + rx * math.cos(math.radians(a)), cy + ry * math.sin(math.radians(a))) for a in range(0, 360, 12)]


def R(x, y, w, h, r=0.0):
    if r <= 0:
        return [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
    r = min(r, w / 2, h / 2)
    return (_arc(x + w - r, y + r, r, -90, 0, 4) + _arc(x + w - r, y + h - r, r, 0, 90, 4)
            + _arc(x + r, y + h - r, r, 90, 180, 4) + _arc(x + r, y + r, r, 180, 270, 4))


def P(*pts):
    return list(pts)


def L(x1, y1, x2, y2, w=2.0):
    d = math.hypot(x2 - x1, y2 - y1) or 1.0
    ox, oy = -(y2 - y1) / d * w / 2, (x2 - x1) / d * w / 2
    return [(x1 + ox, y1 + oy), (x2 + ox, y2 + oy), (x2 - ox, y2 - oy), (x1 - ox, y1 - oy)]


def A(cx, cy, r, a0, a1, w=2.0):
    """굵기 w 의 원호 띠(칠하기 전용, 오목할 수 있다)."""
    return _arc(cx, cy, r + w / 2, a0, a1) + _arc(cx, cy, r - w / 2, a0, a1)[::-1]


def PIE(cx, cy, r, a0, a1):
    return [(cx, cy)] + _arc(cx, cy, r, a0, a1)


def STAR(cx, cy, ro, ri, n=5):
    return [(cx + (ro if i % 2 == 0 else ri) * math.cos(math.radians(-90 + 180 * i / n)),
             cy + (ro if i % 2 == 0 else ri) * math.sin(math.radians(-90 + 180 * i / n))) for i in range(2 * n)]


def RR(cx, cy, w, r0, r1, deg):
    """중심에서 deg 방향으로 r0~r1 구간에 놓인 폭 w 막대(톱니·바늘)."""
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return L(cx + c * r0, cy + s * r0, cx + c * r1, cy + s * r1, w)


def area(pts):
    return sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts))) / 2


def _cr(a, b, p):
    return (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])


def _clip(pts, a, b, sign):
    """윤곽 pts 를 반평면 sign*cross(a,b,p) >= 0 으로 자른다."""
    out, n = [], len(pts)
    for i in range(n):
        p, q = pts[i], pts[(i + 1) % n]
        fp, fq = sign * _cr(a, b, p), sign * _cr(a, b, q)
        if fp >= 0:
            out.append(p)
        if (fp >= 0) != (fq >= 0):
            t = fp / (fp - fq)
            out.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    return out


def is_convex(pts):
    n = len(pts)
    return all(_cr(pts[i], pts[(i + 1) % n], pts[(i + 2) % n]) >= -1e-9 for i in range(n))


class Builder:
    """칠하기·도려내기를 순서대로 쌓아 같은 방향 윤곽 목록을 만든다."""

    def __init__(self):
        self.c = []

    def f(self, *shapes):
        for s in shapes:
            self.c.append(s if area(s) > 0 else s[::-1])

    def x(self, *shapes):
        for s in shapes:
            s = s if area(s) > 0 else s[::-1]
            if not is_convex(s):
                raise ValueError("도려내기 도형은 볼록해야 한다")
            out, n = [], len(s)
            for piece in self.c:
                for i in range(n):            # 영역 i = 변 i 바깥 ∩ 앞선 변들 안쪽(서로 겹치지 않는 분할)
                    q = _clip(piece, s[i], s[(i + 1) % n], -1)
                    for j in range(i):
                        if len(q) < 3:
                            break
                        q = _clip(q, s[j], s[(j + 1) % n], 1)
                    if len(q) >= 3 and abs(area(q)) > 1e-3:
                        out.append(q)
            self.c = out


