def build(glyph, badge=None, badge_only_k=None):
    """(글리프, 보조 표지) → 윤곽 목록. badge_only_k 를 주면 표지 하나를 격자 가운데에 크게 그린다."""
    b = Builder()
    if badge_only_k:
        BADGES[badge](b, 12, 12, badge_only_k)
        return b.c
    GLYPHS[glyph](b)
    if badge:
        b.x(C(*HALO))
        BADGES[badge](b, *BADGE_AT)
    return b.c


def _num(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def to_path(contours):
    """윤곽 목록 → 경로 문자열(Mx,yLx,yLx,y…Z 반복, 점마다 L 명시). 0.01 단위로 반올림하고 같은 점 연속은 하나로 줄인다."""
    parts = []
    for c in contours:
        pts = []
        for x, y in c:
            p = (_num(x), _num(y))
            if not pts or pts[-1] != p:
                pts.append(p)
        if len(pts) > 1 and pts[0] == pts[-1]:
            pts.pop()
        if len(pts) >= 3:
            parts.append("M" + ",".join(pts[0]) + "".join("L" + ",".join(p) for p in pts[1:]) + "Z")
    return "".join(parts)
